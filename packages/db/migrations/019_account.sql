-- The guest's account (D44), platform communications (D45), the owner's history
-- (D47) and external identities for the sign-in with Google (D48).

-- The generated password must be changed at the first sign-in (D44).
ALTER TABLE app_user ADD COLUMN must_change_password boolean NOT NULL DEFAULT false;

-- One account may carry several external identities; a provider+subject pair
-- belongs to exactly one account. Like app_user and session, the application
-- role reaches this table only through the SECURITY DEFINER functions below.
CREATE TABLE user_identity (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES app_user (id),
  provider text NOT NULL,
  subject text NOT NULL,
  email text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (provider, subject)
);
ALTER TABLE user_identity ENABLE ROW LEVEL SECURITY;

-- Platform rows (D45): account mails and account actions belong to no beach club.
-- The beach-scoped policies compare beach_id = app_beach_id(), which a NULL beach
-- never matches: no beach-scoped listing can ever show a platform row. The worker
-- claims and finishes queue rows through SECURITY DEFINER functions, which see
-- every row, platform ones included.
ALTER TABLE outbox ALTER COLUMN beach_id DROP NOT NULL;
ALTER TABLE notification ALTER COLUMN beach_id DROP NOT NULL;
ALTER TABLE audit_event ALTER COLUMN beach_id DROP NOT NULL;

CREATE POLICY outbox_platform_write ON outbox FOR INSERT TO ombre_app
  WITH CHECK (beach_id IS NULL);
-- Platform notifications are written by the worker and readable only outside any
-- beach context (no management page lists them yet; the platform console is deferred).
CREATE POLICY notification_platform ON notification TO ombre_app
  USING (beach_id IS NULL AND app_beach_id() IS NULL) WITH CHECK (beach_id IS NULL);

-- The history (D47): a confirmed stay may belong to an account. Filled by
-- account_relink below; the application role still never updates the group.
ALTER TABLE booking_group ADD COLUMN user_id uuid REFERENCES app_user (id);
CREATE INDEX booking_group_by_user ON booking_group (user_id) WHERE user_id IS NOT NULL;

-- The owner path (D47): with app.user_id set and no beach context, the signed-in
-- guest reads their own groups and the rows that hang off them. SELECT-only
-- policies: inserts and updates keep answering to the beach-scoped policies alone.
CREATE POLICY booking_group_owner_read ON booking_group FOR SELECT TO ombre_app
  USING (app_beach_id() IS NULL AND user_id = app_user_id());
CREATE POLICY booking_owner_read ON booking FOR SELECT TO ombre_app
  USING (app_beach_id() IS NULL AND EXISTS (
    SELECT 1 FROM booking_group g WHERE g.id = booking.group_id AND g.user_id = app_user_id()));
CREATE POLICY pass_owner_read ON pass FOR SELECT TO ombre_app
  USING (app_beach_id() IS NULL AND EXISTS (
    SELECT 1 FROM booking_group g WHERE g.id = pass.group_id AND g.user_id = app_user_id()));
CREATE POLICY payment_owner_read ON payment FOR SELECT TO ombre_app
  USING (app_beach_id() IS NULL AND EXISTS (
    SELECT 1 FROM booking_group g WHERE g.id = payment.group_id AND g.user_id = app_user_id()));
CREATE POLICY booking_extra_owner_read ON booking_extra FOR SELECT TO ombre_app
  USING (app_beach_id() IS NULL AND EXISTS (
    SELECT 1 FROM booking_group g WHERE g.id = booking_extra.group_id AND g.user_id = app_user_id()));

-- Public registration (D44). The password is generated by the caller and travels
-- only through the mail queue; the answer never says whether the email was known.
-- Platform audit rows (beach NULL) are written here, where the actor is certain.
CREATE FUNCTION account_register(p_email text, p_name text, p_password text) RETURNS text
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp
AS $$
DECLARE
  v_existing uuid;
  v_created uuid;
BEGIN
  SELECT id INTO v_existing FROM app_user WHERE email = lower(p_email);
  IF FOUND THEN
    INSERT INTO audit_event (beach_id, actor_user_id, action, detail)
      VALUES (NULL, v_existing, 'account.register', '{"outcome": "exists"}');
    RETURN 'exists';
  END IF;
  INSERT INTO app_user (email, name, password_hash, must_change_password)
    VALUES (lower(p_email), p_name, crypt(p_password, gen_salt('bf', 12)), true)
    RETURNING id INTO v_created;
  INSERT INTO audit_event (beach_id, actor_user_id, action, detail)
    VALUES (NULL, v_created, 'account.register', '{"outcome": "created"}');
  -- Earlier stays made without an account, with this same email, join the history (D47).
  PERFORM account_relink(v_created, p_email);
  RETURN 'created';
END
$$;

-- Change of password, forced at the first sign-in and free afterwards (D44).
CREATE FUNCTION account_change_password(p_user uuid, p_old text, p_new text) RETURNS text
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp
AS $$
DECLARE
  u app_user%ROWTYPE;
BEGIN
  SELECT * INTO u FROM app_user WHERE id = p_user FOR UPDATE;
  IF NOT FOUND OR u.disabled THEN
    RETURN 'invalid';
  END IF;
  IF crypt(p_old, u.password_hash) <> u.password_hash THEN
    RETURN 'invalid';
  END IF;
  UPDATE app_user
    SET password_hash = crypt(p_new, gen_salt('bf', 12)), must_change_password = false
    WHERE id = u.id;
  INSERT INTO audit_event (beach_id, actor_user_id, action, detail)
    VALUES (NULL, u.id, 'account.change_password', '{}');
  RETURN 'ok';
END
$$;

-- Sign-in with an external identity (D48): finds the identity, or links it to the
-- account with the same email, or creates the account there with an unknown random
-- password and no forced change. Opens a session like auth_login.
CREATE FUNCTION account_identity_login(p_provider text, p_subject text, p_email text, p_name text, p_token_hash text, p_ttl_seconds integer)
  RETURNS TABLE (o_outcome text, o_user_id uuid, o_email text, o_name text, o_platform_role platform_role, o_totp_enabled boolean, o_must_change_password boolean, o_expires_at timestamptz)
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp
AS $$
DECLARE
  v_user uuid;
  u app_user%ROWTYPE;
  v_expires timestamptz;
BEGIN
  SELECT user_id INTO v_user FROM user_identity
    WHERE provider = p_provider AND subject = p_subject;
  IF NOT FOUND THEN
    SELECT id INTO v_user FROM app_user WHERE email = lower(p_email);
    IF NOT FOUND THEN
      INSERT INTO app_user (email, name, password_hash, must_change_password)
        VALUES (lower(p_email), p_name, crypt(encode(gen_random_bytes(32), 'hex'), gen_salt('bf', 12)), false)
        RETURNING id INTO v_user;
    END IF;
    INSERT INTO user_identity (user_id, provider, subject, email)
      VALUES (v_user, p_provider, p_subject, lower(p_email));
    INSERT INTO audit_event (beach_id, actor_user_id, action, detail)
      VALUES (NULL, v_user, 'account.identity_link', jsonb_build_object('provider', p_provider));
  END IF;
  SELECT * INTO u FROM app_user WHERE id = v_user;
  IF u.disabled THEN
    RETURN QUERY SELECT 'invalid'::text, NULL::uuid, NULL::text, NULL::text, NULL::platform_role, NULL::boolean, NULL::boolean, NULL::timestamptz;
    RETURN;
  END IF;
  UPDATE app_user SET failed_logins = 0, locked_until = NULL WHERE id = u.id;
  INSERT INTO session (user_id, token_hash, expires_at)
    VALUES (u.id, p_token_hash, now() + make_interval(secs => p_ttl_seconds))
    RETURNING session.expires_at INTO v_expires;
  RETURN QUERY SELECT 'ok'::text, u.id, u.email, u.name, u.platform_role, u.totp_enabled, u.must_change_password, v_expires;
END
$$;

-- Hands the orphan groups whose guest email matches over to the account (D47):
-- at the registration and at every successful sign-in. Never undone.
CREATE FUNCTION account_relink(p_user uuid, p_email text) RETURNS integer
  LANGUAGE sql SECURITY DEFINER SET search_path = public, pg_temp
AS $$
  WITH changed AS (
    UPDATE booking_group g SET user_id = p_user
    WHERE g.user_id IS NULL AND EXISTS (
      SELECT 1 FROM booking b WHERE b.group_id = g.id AND lower(b.guest_email) = lower(p_email))
    RETURNING 1
  )
  SELECT count(*)::integer FROM changed
$$;

-- The session now also says whether the password change is still owed.
DROP FUNCTION auth_session(text);
CREATE FUNCTION auth_session(p_token_hash text)
  RETURNS TABLE (o_user_id uuid, o_email text, o_name text, o_platform_role platform_role, o_totp_enabled boolean, o_must_change_password boolean)
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp
AS $$
  SELECT u.id, u.email, u.name, u.platform_role, u.totp_enabled, u.must_change_password
  FROM session s JOIN app_user u ON u.id = s.user_id
  WHERE s.token_hash = p_token_hash AND s.revoked_at IS NULL AND s.expires_at > now() AND NOT u.disabled
$$;

REVOKE ALL ON FUNCTION account_register(text, text, text), account_change_password(uuid, text, text), account_identity_login(text, text, text, text, text, integer), account_relink(uuid, text), auth_session(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION account_register(text, text, text), account_change_password(uuid, text, text), account_identity_login(text, text, text, text, text, integer), account_relink(uuid, text), auth_session(text) TO ombre_app;
